// LIQD risk levels are integers on the wire: { LOW: 1, MEDIUM: 2, HIGH: 3, WTF: 4 }.
export const RISK_LEVELS = [1, 2, 3, 4];
export const RISK_LABELS = { 1: 'Low', 2: 'Medium', 3: 'High', 4: 'WTF' };

/** Effective row count for a config — WTF forces the board to 13 rows. */
export function effectiveRows(rows, riskLevel) {
  return riskLevel === WTF_RISK_LEVEL ? WTF_ROWS : rows;
}

/** The full multiplier array for a (rows, riskLevel) config. */
export function multipliersFor(rows, riskLevel) {
  if (riskLevel === WTF_RISK_LEVEL) return PLINKO_WTF_ODDS;
  return PAYOUT_TABLES[rows][riskLevel];
}

/** Table lookup for a landing slot. */
export function paytable(rows, riskLevel, slot) {
  return multipliersFor(rows, riskLevel)[slot];
}

/** Total number of slots for a config. 8-row board → 9 slots; WTF → 14. */
export function slotCount(rows, riskLevel = 1) {
  return effectiveRows(rows, riskLevel) + 1;
}
