#!/usr/bin/env node
/** Build the dependency-free entry points from the checked-in TypeScript sources. */
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const relative = p => path.relative(root, p).split(path.sep).join('/');
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const p = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(p) : [p];
  }).sort();
}
const sources = ['src', 'tests'].flatMap(dir => walk(path.join(root, dir)))
  .filter(p => p.endsWith('.ts'));
const unitEntries = sources.filter(p => p.endsWith('Tests.ts')).map(relative);
if (unitEntries.length === 0) throw new Error('No unit-test sources found.');
const configPath = path.join(root, 'tsconfig.json');
const config = ts.readConfigFile(configPath, ts.sys.readFile);
if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
const outDir = path.join(root, '.standalone-emit');
const options = {
  ...parsed.options, rootDir: root, outDir,
  module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020,
  noEmit: false, noEmitOnError: true, declaration: false,
  sourceMap: false, inlineSourceMap: false, removeComments: true,
  incremental: false, composite: false,
};
const runtime = fs.readFileSync(path.join(root, 'scripts/standalone-runtime.cjs'), 'utf8');
const products = {};
for (const [output, entries, unit] of [
  ['test.js', unitEntries, true],
  ['verify.js', ['tests/verify.ts'], false],
  ['replay.js', ['src/replay.ts'], false],
]) {
  const program = ts.createProgram(entries.map(p => path.join(root, p)), options);
  const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
  if (diagnostics.length) {
    throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
      getCanonicalFileName: p => p,
      getCurrentDirectory: () => root,
      getNewLine: () => '\n',
    }));
  }
  const modules = new Map();
  const emitted = program.emit(undefined, (filename, body) => {
    if (!filename.endsWith('.js')) throw new Error(`Unexpected compiler output: ${filename}`);
    modules.set(path.relative(outDir, filename).split(path.sep).join('/'), body);
  });
  if (emitted.emitSkipped) throw new Error(`Compilation skipped for ${output}`);
  const wrappers = [...modules].sort(([a], [b]) => a.localeCompare(b, 'en'))
    .map(([id, body]) => `${JSON.stringify(id)}: function(module, exports, require, __filename, __dirname) {\n${body}\n}`)
    .join(',\n');
  products[output] = `// Generated from TypeScript by npm run build. Do not edit this file directly.\n`
    + `'use strict';\nconst __modules = {\n${wrappers}\n};\n`
    + runtime + '\n'
    + (unit ? '__installTestGlobals();\n' : '')
    + entries.map(p => `__load(${JSON.stringify(p.replace(/\.ts$/, '.js'))});`).join('\n') + '\n';
}
const hash = value => createHash('sha256').update(value).digest('hex');
const inputs = [...sources.map(relative),
  'tsconfig.json', '.mocharc.yml', 'package-lock.json',
  'scripts/build-standalone.mjs', 'scripts/check-standalone.mjs',
  'scripts/standalone-runtime.cjs',
].sort();
const manifest = {
  format: 1,
  compiler: { name: 'typescript', version: ts.version },
  unitEntries,
  inputs: Object.fromEntries(inputs.map(p => [p, hash(fs.readFileSync(path.join(root, p)))])),
  outputs: Object.fromEntries(Object.entries(products).map(([p, body]) => [p, hash(body)])),
};
products['standalone-manifest.json'] = JSON.stringify(manifest, null, 2) + '\n';
let differences = 0;
for (const [name, body] of Object.entries(products)) {
  const target = path.join(root, name);
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== body) {
      console.error(`[build] ${name} differs from the source build.`);
      differences++;
    }
  } else fs.writeFileSync(target, body);
}
if (differences) process.exit(1);
console.log(`[build] ${check ? 'Reproduced' : 'Built'} test.js, verify.js and replay.js; ${unitEntries.length} unit-test source files; TypeScript ${ts.version}.`);
