#!/usr/bin/env node
/**
 * build-docs — evidence.md, exploit-testing.md and SUMMARY.md are EXTRACTS, not second copies.
 *
 * MANIFEST.md is the one source for the evidence register, the integrity (S5) matrix and the
 * mutation-battery paragraphs; tests/mutations.json and tests/mutations-extra.json are the one source
 * for the list of counterexamples. This script cuts those blocks out and writes the three documents.
 *
 *   node scripts/build-docs.mjs           write the three documents
 *   node scripts/build-docs.mjs --check   exit 1 if any of them is not exactly what this script would
 *                                         write (scripts/check-outputs.mjs runs this inside npm test, so
 *                                         a fact edited in one place and not the other fails the suite)
 * Plain Node, no dependencies.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(ROOT, f), 'utf8');
const manifest = read('MANIFEST.md');
const lines = manifest.split('\n');
const between = (startRe, endRe) => {
  const a = lines.findIndex((l) => startRe.test(l));
  if (a < 0) throw new Error(`MANIFEST.md: no line matching ${startRe}`);
  const rel = lines.slice(a + 1).findIndex((l) => endRe.test(l));
  return lines.slice(a + 1, rel < 0 ? undefined : a + 1 + rel).join('\n').trim();
};
const paragraph = (startRe) => {
  const l = lines.find((x) => startRe.test(x));
  if (!l) throw new Error(`MANIFEST.md: no paragraph matching ${startRe}`);
  return l;
};
const NOTE = (what) => `> Generated by \`node scripts/build-docs.mjs\` from ${what}. Do not edit this file: edit the source and run the script. \`npm test\` fails if the two disagree.`;

// ── evidence.md ───────────────────────────────────────────────────────────────
const evidence = [
  '# LIQD Plinko — Evidence register',
  '',
  NOTE('the Evidence section of [MANIFEST.md](MANIFEST.md#evidence)'),
  '',
  between(/^## Evidence$/, /^## /),
  '',
].join('\n');

// ── exploit-testing.md ────────────────────────────────────────────────────────
const regs = [['tests/mutations.json', 'Scored-step counterexamples'], ['tests/mutations-extra.json', 'Publication-guard refusals, reviewer configurations and the declared survivor']];
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const regTables = regs.map(([file, title]) => {
  const arr = JSON.parse(read(file));
  const rows = arr.map((m) => {
    const sp = m.name.indexOf(' ');
    const expected = m.expectSurvive
      ? `declared survivor: steps ${(m.expectFail ?? []).join(', ')} reject it, the other ${(m.expectPass ?? []).length} pass`
      : (m.expect ?? (m.expectVerdict ? `verdict ${m.expectVerdict}` : ''));
    return `| \`${cell(m.name.slice(0, sp))}\` | ${cell(m.name.slice(sp + 1))} | ${cell(m.runner ?? 'verify')} | ${cell(expected)} |`;
  });
  return [`### ${title} (\`${file}\`, ${arr.length} entries)`, '', '| ID | What is changed | Runner | Must produce |', '|---|---|---|---|', ...rows].join('\n');
});
const exploit = [
  '# LIQD Plinko — Integrity, forgery and mutation testing',
  '',
  NOTE('[MANIFEST.md](MANIFEST.md#integrity-matrix) (the S5 fairness-integrity matrix and the battery paragraphs) and the two mutation registries'),
  '',
  '## S5: fairness-integrity matrix',
  '',
  between(/^### Integrity matrix$/, /^### /),
  '',
  '## Mutation battery',
  '',
  paragraph(/^\*\*Mutation battery\.\*\*/),
  '',
  paragraph(/^`S00` changes /),
  '',
  ...regTables.flatMap((t) => [t, '']),
].join('\n');

// ── SUMMARY.md ────────────────────────────────────────────────────────────────
const slug = (h) => h.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ +/g, '-');
const sections = lines.filter((l) => /^## /.test(l) && l !== '## Contents').map((l) => l.slice(3));
const summary = [
  '# Summary',
  '',
  NOTE('the section headings of [MANIFEST.md](MANIFEST.md)'),
  '',
  '* [LIQD Plinko — Provably Fair Audit](README.md)',
  '* [Consolidated audit overview](MANIFEST.md)',
  ...sections.map((s) => `  * [${s}](MANIFEST.md#${slug(s)})`),
  '* [Evidence register](evidence.md)',
  '* [Integrity, forgery and mutation testing](exploit-testing.md)',
  '* [Algorithm specification](docs/ALGORITHM.md)',
  '* [Module interface](docs/INTERFACE.md)',
  '',
].join('\n');

const out = { 'evidence.md': evidence, 'exploit-testing.md': exploit, 'SUMMARY.md': summary };
const CHECK = process.argv.includes('--check');
let bad = 0;
for (const [f, text] of Object.entries(out)) {
  const p = path.join(ROOT, f);
  if (CHECK) {
    const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (cur !== text) { console.error(`  [build-docs] ${f} is ${cur === null ? 'MISSING' : 'STALE'}: it is not what MANIFEST.md and the registries produce. Run node scripts/build-docs.mjs.`); bad++; }
  } else fs.writeFileSync(p, text);
}
if (CHECK && !bad) console.log(`  [build-docs] OK: ${Object.keys(out).join(', ')} equal their sources`);
if (!CHECK) console.log(`  [build-docs] wrote ${Object.keys(out).join(', ')}`);
process.exit(bad ? 1 : 0);
